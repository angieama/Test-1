import assert from 'node:assert/strict';
import { createBrowserApi, STORAGE_KEY } from '../static/browser-api.ts';
const records = new Map();
const storage = { getItem:key=>records.get(key)??null, setItem:(key,value)=>records.set(key,value) };
let now=Date.parse('2026-10-27T10:00:00+03:00');
let transport=createBrowserApi(storage,()=>now);
async function api(path,body,method=body?'POST':'GET',status=200){const response=await transport(path,{method,...(body?{body:JSON.stringify(body)}:{})});const data=await response.json();assert.equal(response.status,status,JSON.stringify(data));return data;}
let data=await api('/api/payments');
const oldRide=data.journeys.find(j=>j.endedAt===null);
const exact=data.payments.find(p=>p.journeyId===oldRide.id&&p.amountCents===oldRide.fareCents);
await api(`/api/payments/${exact.id}/verify`,{});
// Upgrade an already-existing browser ledger that predates saved routes.
const legacy=JSON.parse(records.get(STORAGE_KEY));delete legacy.routes;delete legacy.routeNamesVersion;legacy.journeys.find(j=>j.id===oldRide.id).origin='Nairobi';records.set(STORAGE_KEY,JSON.stringify(legacy));
assert.deepEqual((await api('/api/routes')).routes,[]);
assert.equal((await api('/api/payments')).journeys.find(j=>j.id===oldRide.id).origin,'Kileleshwa');
assert.equal(JSON.parse(records.get(STORAGE_KEY)).routeNamesVersion,1);
assert.equal((await api('/api/payments')).payments.find(p=>p.id===exact.id).verifiedAt,now);
const saved=await api('/api/routes',{origin:'Nairobi',destination:'Westlands',fare:'150'});
assert.equal((await api('/api/payments')).journeys.length,data.journeys.length,'Saving a route must not create a ride');
await api(`/api/routes/${saved.id}`,{origin:'Nairobi',destination:'Westlands',fare:'175'},'PATCH');
assert.equal((await api('/api/payments')).journeys.find(j=>j.id===oldRide.id).fareCents,10000);
await api('/api/routes',{origin:'Town',destination:'Town',fare:'100'},'POST',422);
await api('/api/routes',{origin:'Town',destination:'Nairobi',fare:'0'},'POST',422);
await api('/api/routes/missing',{origin:'Town',destination:'Nairobi',fare:'100'},'PATCH',404);
await api(`/api/journeys/${oldRide.id}`,{action:'end',cash:'500'},'PATCH');
const picked=(await api('/api/routes')).routes[0];
now+=10000;
const fresh=await api('/api/journeys',{origin:picked.origin,destination:picked.destination,fare:'200'});
assert.notEqual(fresh.id,oldRide.id);
data=await api('/api/payments?journey='+fresh.id);
const ride=data.journeys.find(j=>j.id===fresh.id);
assert.equal(ride.fareCents,20000);assert.equal(ride.cashCents,0);assert.equal(ride.paymentCount,0);assert.equal(ride.passengerCount,0);assert.equal(ride.totalCents,0);
assert.equal((await api('/api/routes')).routes[0].fareCents,17500,'One-ride fare override must not change a saved route');
assert.equal(data.journeys.find(j=>j.id===oldRide.id).cashCents,50000);
assert.equal(data.payments.find(p=>p.id===exact.id).journeyId,oldRide.id);
await api('/api/journeys',{origin:picked.origin,destination:picked.destination,fare:'200'},'POST',409);
await api(`/api/journeys/${fresh.id}`,{action:'end',cash:'0'},'PATCH');
const repeated=await api('/api/journeys',{origin:oldRide.origin,destination:oldRide.destination,fare:String(oldRide.fareCents/100)});
assert.notEqual(repeated.id,oldRide.id);assert.notEqual(repeated.id,fresh.id);
transport=createBrowserApi(storage,()=>now);
assert.equal((await api('/api/routes')).routes[0].id,saved.id);
console.log('PASS: legacy records preserved, saved routes persist/edit, one-ride fare overrides stay separate, repeated rides use new IDs with zero cash/receipts/passengers, original records stay locked, and one-active-ride guard remains');
